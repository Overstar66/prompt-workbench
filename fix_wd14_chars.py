def work_suffix(en):
    """从 artoria_pendragon_(fate) 里取出作品中文名，取不到返回 ''。"""
    if not en.endswith(")"):
        return ""
    i = en.rfind("(")
    if i < 0:
        return ""
    w = en[i + 1:-1]
    for k in ("second_ascension", "third_ascension", "first_ascension"):
        w = w.replace(k + ")", "")
    return WORK_ZH.get(w, "")



def backup(path):
    ts = time.strftime("%Y%m%d_%H%M%S")
    dst = os.path.join(HERE, "tags_cn.backup_charfix_%s.json" % ts)
    if os.path.exists(dst):
        return dst
    shutil.copy2(path, dst)
    return dst


def fix_typo(s):
    """修 '蓝色色眼睛' 这类重复字缺陷。"""
    if not s:
        return s
    out = s.replace("色色", "色").replace("眼睛眼睛", "眼睛")
    return out


def main():
    dry = "--dry-run" in sys.argv
    with open(TAGS, encoding="utf-8") as f:
        doc = json.load(f)
    tags = doc["tags"]

    targets = [t for t in tags if t.get("cat") == CAT_ROLE and t.get("sub") == SUB_SRC]

    # 已有的中文名 -> 条目列表（用于防重名）
    zh_map = {}
    for t in tags:
        zh_map.setdefault((t.get("cat"), t.get("zh")), []).append(t)

    def occupied_by_other(cat, name, me):
        return any(x is not me for x in zh_map.get((cat, name), ()))

    n_nonchar, n_rename, n_app, n_typo = 0, 0, 0, 0
    renamed_log, nonchar_log, app_log, skipped, dupname_log = [], [], [], [], []

    for i, t in enumerate(targets, 1):
        en = t.get("en") or ""
        zh = t.get("zh") or ""

        # ① 非角色 → 改分类
        if en in NONCHAR:
            cat, sub, new_zh = NONCHAR[en]
            if t.get("cat") != cat or t.get("sub") != sub or (new_zh and zh != new_zh):
                nonchar_log.append("%s（%s）→ %s / %s%s" % (
                    zh, en, cat, sub, ("，改名 " + new_zh) if (new_zh and new_zh != zh) else ""))
                if not dry:
                    t["cat"] = cat
                    t["sub"] = sub
                    if new_zh:
                        t["zh"] = new_zh
                n_nonchar += 1

        # ② 中文名纠正
        elif en in RENAME:
            want = RENAME[en]
            if zh != want:
                old = zh
                if occupied_by_other(t.get("cat"), want, t):
                    # 撞上已有条目：优先加作品后缀保持唯一
                    wk = work_suffix(en)
                    alt = want + "（%s）" % wk if wk else ""
                    if alt and (zh == alt or not occupied_by_other(t.get("cat"), alt, t)):
                        want = alt
                    else:
                        # 没有作品名可加：允许同名（同角色的不同 en 别名）
                        dupname_log.append("%s → %s（%s）" % (old, want, en))
                renamed_log.append("%s → %s（%s）" % (old, want, en))
                if not dry:
                    lst = zh_map.get((t.get("cat"), old))
                    if lst and t in lst:
                        lst.remove(t)
                    t["zh"] = want
                zh_map.setdefault((t.get("cat"), want), []).append(t)
                n_rename += 1

        # ③ 补 app（覆盖式写入有把握的字段）
        if en in APP and t.get("cat") == CAT_ROLE and en not in NONCHAR:
            want = APP[en]
            cur = t.get("app") or {}
            changed = False
            for k in BODY_KEYS:
                v = want.get(k)
                if v and cur.get(k) != v:
                    if not dry:
                        cur[k] = v
                        t["app"] = cur
                    changed = True
            if changed:
                app_log.append("%s（%s）" % (t.get("zh"), en))
                n_app += 1

        # 已有的 app 值修重复字缺陷
        a = t.get("app") or {}
        for k in BODY_KEYS:
            v = a.get(k)
            if v and fix_typo(v) != v:
                if not dry:
                    a[k] = fix_typo(v)
                n_typo += 1

        if i % 100 == 0:
            print("进度 %d/%d" % (i, len(targets)), flush=True)

    if dry:
        print("\n[DRY-RUN] 非角色 %d，改名 %d，补 app %d，修重复字 %d" %
              (n_nonchar, n_rename, n_app, n_typo))
        for ln in nonchar_log[:60]:
            print("  N " + ln)
        for ln in renamed_log[:60]:
            print("  R " + ln)
        for ln in app_log[:30]:
            print("  A " + ln)
        for ln in skipped[:30]:
            print("  ! " + ln)
        return

    if n_nonchar or n_rename or n_app or n_typo:
        bk = backup(TAGS)
        print("已备份 → %s" % bk)
        tmp = TAGS + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(doc, f, ensure_ascii=False, indent=1)
        os.replace(tmp, TAGS)
    else:
        print("changed 0：没有需要修改的条目")

    print("\n=== 汇总 ===")
    print("非角色重新归类：%d" % n_nonchar)
    for ln in nonchar_log:
        print("  N " + ln)
    print("中文名纠正：%d" % n_rename)
    for ln in renamed_log[:20]:
        print("  R " + ln)
    print("补 app：%d" % n_app)
    for ln in app_log[:10]:
        print("  A " + ln)
    print("修重复字：%d" % n_typo)
    if skipped:
        print("跳过（重名冲突）：%d" % len(skipped))
        for ln in skipped:
            print("  ! " + ln)

    # 报告文件（有改动才重写，避免空报告覆盖上次结果）
    if not (n_nonchar or n_rename or n_app or n_typo):
        return
    rep = os.path.join(HERE, "fix_wd14_chars_report.txt")
    with open(rep, "w", encoding="utf-8") as f:
        f.write("非角色重新归类 %d 条\n" % n_nonchar)
        for ln in nonchar_log:
            f.write("  " + ln + "\n")
        f.write("\n中文名纠正 %d 条\n" % n_rename)
        for ln in renamed_log:
            f.write("  " + ln + "\n")
        f.write("\n补 app %d 条\n" % n_app)
        for ln in app_log:
            f.write("  " + ln + "\n")
        f.write("\n修重复字 %d 条\n" % n_typo)
        if skipped:
            f.write("\n跳过 %d 条\n" % len(skipped))
            for ln in skipped:
                f.write("  " + ln + "\n")
        if dupname_log:
            f.write("\n同名条目 %d 条（另一条精品条目已用同名）\n" % len(dupname_log))
            for ln in dupname_log:
                f.write("  " + ln + "\n")
    print("报告 → %s" % rep)


if __name__ == "__main__":
    main()
