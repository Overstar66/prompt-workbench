def _s(x):
    return " ".join(str(x or "").split())


def build_entries():
    """把 RAW 整理成 tags_cn.json 的条目结构，并在本表内部按 en 去重。"""
    out, seen = [], set()
    for row in RAW:
        if len(row) != 8:
            raise SystemExit("数据行字段数不对（应为 8）：%r" % (row,))
        zh, en, sub, hair, eyes, outfit, body, chest = (_s(x) for x in row)
        en = en.lower()
        if not zh or not en or not sub:
            raise SystemExit("数据行缺少 zh/en/sub：%r" % (row,))
        if en in seen:
            continue
        seen.add(en)
        out.append({
            "zh": zh, "en": en, "cat": "角色", "sub": sub, "nsfw": False,
            "app": {"hair": hair, "eyes": eyes, "outfit": outfit,
                    "body": body, "chest": chest},
        })
    return out


def existing_keys():
    """已有角色（tags_cn.json + chars_extra.json）的 en 与 zh 集合。"""
    ens, zhs = set(), set()
    with open(PATH, "rb") as f:
        base = json.loads(f.read().decode("utf-8"))["tags"]
    sources = [base]
    if os.path.exists(EXTRA):
        try:
            with open(EXTRA, "rb") as f:
                extra = json.loads(f.read().decode("utf-8"))
            if isinstance(extra, list):
                sources.append(extra)
        except Exception:
            pass
    for arr in sources:
        for t in arr:
            if not isinstance(t, dict) or t.get("cat") != "角色":
                continue
            ens.add(_s(t.get("en")).lower())
            zhs.add(_s(t.get("zh")))
    return ens, zhs, base


def backup_name():
    stamp = time.strftime("%Y%m%d_%H%M")
    p = os.path.join(HERE, "tags_cn.backup_chars_%s.json" % stamp)
    n = 1
    while os.path.exists(p):
        n += 1
        p = os.path.join(HERE, "tags_cn.backup_chars_%s_%d.json" % (stamp, n))
    return p


def main():
    dry = "--dry-run" in sys.argv
    ens, zhs, tags = existing_keys()
    cand = build_entries()
    add = [e for e in cand if e["en"] not in ens and e["zh"] not in zhs]
    dup_en = sum(1 for e in cand if e["en"] in ens)
    dup_zh = sum(1 for e in cand if e["en"] not in ens and e["zh"] in zhs)
    print("数据表 %d 条；已存在(en) %d 条；已存在(zh) %d 条；待追加 %d 条"
          % (len(cand), dup_en, dup_zh, len(add)))
    if not add:
        print("没有新角色，文件未改动。")
        return
    if dry:
        print("--dry-run：不写文件。")
        return

    bak = backup_name()
    shutil.copyfile(PATH, bak)
    print("已备份：%s" % os.path.basename(bak))

    tags.extend(add)
    data = {"version": 3,
            "order": "按画面重要性排序",
            "tags": tags}
    raw = json.dumps(data, ensure_ascii=False, indent=1).replace("\n", "\r\n")
    tmp = PATH + ".tmp"
    with open(tmp, "wb") as f:
        f.write(raw.encode("utf-8"))
    os.replace(tmp, PATH)

    chars = [t for t in tags if isinstance(t, dict) and t.get("cat") == "角色"]
    empty = sum(1 for e in add for k in FIELDS if not e["app"][k])
    subs = {e["sub"] for e in add}
    print("写入完成：tags %d 条，其中角色 %d 条（本次新增 %d，覆盖 %d 个作品，空字段 %d 个）"
          % (len(tags), len(chars), len(add), len(subs), empty))


if __name__ == "__main__":
    main()
